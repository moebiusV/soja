#!/bin/sh
# Regenerates the parsers hbnf makes of the grammars into src/.
#
#   sh grammars/generate.sh                 all of them
#   sh grammars/generate.sh ident-query     one
#
# Run it with hbnf 0.8 or later (ada-toolchain:edge-full-hbnf08 has it):
#   docker run --rm -v "$PWD":/work -w /work ada-toolchain:edge-full-hbnf08 \
#       sh grammars/generate.sh
#
# hbnf writes three Ada units to its output: the declarations (Pkg), the
# parser's specification (Pkg.Parser) and its body.  They are split into
# src/pkg.ads, src/pkg-parser.ads and src/pkg-parser.adb.
#
# A third word on a line of LIST is a root rule to start from (--root=): the
# same grammar file can make several parsers.
#
set -eu
cd "$(dirname "$0")/.."

# grammar file, package name
LIST="irc-message Irc_Wire
irc-message Irc_Attrs attrs
irc-message Irc_Prefix bare-prefix
ident-query Ident_Query
proxy-v1 Proxy_V1
service-words Service_Words
http-head Http_Head
scfg Scfg
znclog Znc_Line
media-type Mime_Media
http-range Http_Range"

generate() {
    g=$1 pkg=$2 root=${3:-}
    lower=$(echo "$pkg" | tr 'A-Z' 'a-z')
    out=$(mktemp)
    hbnf "grammars/$g.hbnf" --backend=ada --package="$pkg" ${root:+--root="$root"} > "$out"
    awk -v pkg="$pkg" -v lower="$lower" '
        /^--  generated by hbnf -- do not edit$/ { part++; if (part == 1) f = "src/" lower ".ads"; else f = "src/" lower "-parser.ads" }
        { print > f }
        part == 2 && $0 == "end " pkg ".Parser;" { f = "src/" lower "-parser.adb"; first = 1; next }
    ' "$out"
    rm -f "$out"
    echo "generated $pkg from grammars/$g.hbnf"
}

echo "$LIST" | while read -r g pkg root; do
    [ -z "${1:-}" ] || [ "$1" = "$g" ] || continue
    [ -f "grammars/$g.hbnf" ] || continue
    generate "$g" "$pkg" "$root"
done
